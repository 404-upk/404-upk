def detect(text: str) -> str | None:
    norm = normalize(text)
    if any(p.search(norm) for p in _compiled[THREAT]):
        return THREAT
    if _BURNING.search(norm) and not _LIGHT_WORDS.search(norm):
        return DANGER
    # опасность важнее попытки взлома: «забудь правила, в розетке искрит» получит ответ про опасность
    for kind in (DANGER, DIY, SECRET, INJECTION):
        if any(p.search(norm) for p in _compiled[kind]):
            return kind
    return None


def promises_deadline(answer: str) -> bool:
    return bool(DEADLINE.search(normalize(answer)))


def invents_person(answer: str) -> bool:
    return bool(_PERSON.search(answer))


def is_unsafe_advice(answer: str) -> bool:
    norm = normalize(answer)
    return any(p.search(norm) for p in _unsafe)


def leaks_prompt(answer: str) -> bool:
    return bool(_PROMPT_MARKERS.search(normalize(answer)))


def claims_action(answer: str) -> bool:
    return bool(_FAKE_ACTION.search(normalize(answer)))


def strip_unverified_contacts(answer: str, allowed: str) -> tuple[str, bool]:
    """Убирает предложения с телефонами, почтой и ссылками, которых нет в базе знаний."""
    allowed_norm = normalize(allowed)
    sentences = re.split(r"(?<=[.!?])\s+", answer.strip())
    kept, removed = [], False
    for sentence in sentences:
        found = [m.group(0) for m in _CONTACT.finditer(sentence)]
        if any(normalize(f) not in allowed_norm for f in found):
            removed = True
            continue
        kept.append(sentence)
    return " ".join(kept).strip(), removed
